// ─────────────────────────────────────────────────────────────────────────────
// Master Analysis Note
// ─────────────────────────────────────────────────────────────────────────────

export interface AnalysisNote {
  /** UUID — primary key in analysis_notes table */
  id: string;

  /** FK to workbench_documents */
  document_id: string;

  /** FK to workbenches */
  workbench_id: string;

  /** Canonical document type. 'unknown' means pipeline halted. */
  document_type: DocumentType;

  /** Three-dimensional confidence. overall = min of all three. */
  confidence: AnalysisNoteConfidence;

  document_metadata: AnalysisNoteDocumentMetadata;
  parties:           AnalysisNoteParties;
  amounts:           AnalysisNoteAmounts;
  dates:             AnalysisNoteDates;
  document_references: AnalysisNoteReferences;
  business_context:  BusinessContext;
  line_items:        LineItem[];
  evidence:          Record<string, unknown>;
  settlement:        AnalysisNoteSettlement;

  /**
   * Cross-document linkage key.
   * Example: sales_invoice → "INV-1234"
   *          customer_payment_receipt for same invoice → "INV-1234"
   * Enables automatic invoice→payment→settlement matching.
   */
  settlement_key: string | null;

  /**
   * Deterministic event candidate. No AI involved.
   * Always a lookup from INTENT_MAP[document_type].
   */
  event_candidate: EventCandidate;

  /**
   * Lifecycle status.
   * Trade Engine acts on: APPROVED or (DRAFT with overall >= 0.85)
   */
  review_status: ReviewStatus;

  reviewed_by:   string | null;
  reviewed_at:   string | null;
  review_notes:  string | null;

  generator_version: string;

  /** True when a newer Analysis Note exists for this document. */
  is_superseded: boolean;

  created_at: string;
}

