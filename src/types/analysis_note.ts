// ─────────────────────────────────────────────────────────────────────────────
// Three-Dimensional Confidence
// ─────────────────────────────────────────────────────────────────────────────

export interface AnalysisNoteConfidence {
  /** How cleanly the document was OCR-extracted. 0–1. */
  ocr_quality: number;
  /** How certain the classifier is about the document_type. 0–1. */
  classification: number;
  /** Fraction of required fields populated for this document type. 0–1. */
  field_completeness: number;
  /**
   * min(ocr_quality, classification, field_completeness).
   * One weak dimension poisons the whole note.
   * Routing: overall >= 0.85 → auto-route; < 0.85 → Needs Review.
   */
  overall: number;
}

// ─────────────────────────────────────────────────────────────────────────────
// Event Candidate — Deterministic, no AI
// ─────────────────────────────────────────────────────────────────────────────

export interface EventCandidate {
  /**
   * Deterministic mapping from document_type via INTENT_MAP.
   * Never generated by AI. Always a lookup.
   */
  event_type: EventType;
  /**
   * Inherits classification confidence exactly.
   * No additional uncertainty introduced.
   */
  confidence: number;
  /** Always: "Deterministic mapping from document_type='...'" */
  reasoning: string;
}

// ─────────────────────────────────────────────────────────────────────────────
// Business Context — Business language only, no accounting terms
// ─────────────────────────────────────────────────────────────────────────────

export interface BusinessContext {
  /** What happened in the business. e.g. "CUSTOMER_BILLED" */
  intent: EventType;
  /** Direction of cash flow. */
  cash_direction: CashDirection;
  /** Plain English description of economic effect. */
  economic_effect: string;
}

